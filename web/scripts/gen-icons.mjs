import sharp from "sharp";
import { writeFileSync } from "node:fs";

const SPATH =
  "M21.5 10.5C20 8.6 17.9 8 16 8c-3 0-5.5 1.7-5.5 4.2 0 5.6 11 3.3 11 9 0 2.4-2.4 4.3-5.6 4.3-2.3 0-4.4-.8-5.9-2.6";

const grad = `<defs><linearGradient id="g" x1="0" y1="0" x2="512" y2="512" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#38bdf8"/><stop offset="1" stop-color="#7c3aed"/></linearGradient></defs>`;

// Regular icon: rounded square + the SiteVault "S" swoosh in white.
const regular = `<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512">${grad}<rect width="512" height="512" rx="112" fill="url(#g)"/><g transform="translate(96,96) scale(10)" fill="none" stroke="#ffffff" stroke-width="3" stroke-linecap="round" stroke-linejoin="round"><path d="${SPATH}"/></g></svg>`;

// Maskable icon: full-bleed gradient, logo kept inside the ~80% safe zone.
const maskable = `<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512">${grad}<rect width="512" height="512" fill="url(#g)"/><g transform="translate(144,144) scale(7.6)" fill="none" stroke="#ffffff" stroke-width="3" stroke-linecap="round" stroke-linejoin="round"><path d="${SPATH}"/></g></svg>`;

async function png(svg, size) {
  const buf = await sharp(Buffer.from(svg)).resize(size, size).png({ compressionLevel: 9 }).toBuffer();
  return buf.toString("base64");
}

const i192 = await png(regular, 192);
const i512 = await png(regular, 512);
const iMask = await png(maskable, 512);

const out = `// Generated by scripts/gen-icons (sharp, SVG -> PNG). PWA app icons, base64.
// Regenerate if the brand mark changes; keep sizes 192/512 and a maskable 512.
export const ICON_192_PNG = "${i192}";
export const ICON_512_PNG = "${i512}";
export const ICON_MASKABLE_PNG = "${iMask}";
`;
writeFileSync(new URL("./src/pwa-icons.ts", import.meta.url), out);
console.log("wrote src/pwa-icons.ts", { i192: i192.length, i512: i512.length, iMask: iMask.length });
